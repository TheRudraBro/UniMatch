export function getUniversityWebsite(uni) {
  if (!uni) return { url: "#", isDirect: false };
  const direct =
    (uni.website && uni.website.trim()) ||
    (uni.id && universityWebsites[uni.id] && universityWebsites[uni.id].trim());
  if (direct) {
    const normalizedUrl = /^https?:\/\//i.test(direct)
      ? direct
      : `https://${direct}`;
    return { url: normalizedUrl, isDirect: true };
  }
  const query = encodeURIComponent(
    `${uni.name || ""} official website Bangladesh`,
  );
  return {
    url: `https://www.google.com/search?q=${query}`,
    isDirect: false,
  };
}

